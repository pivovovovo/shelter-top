function getRandomElement<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getRandomElements<T>(arr: T[], count: number): T[] {
  const shuffled = [...arr].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function generateCharacterCard(): CharacterCard {
  return {
    profession: getRandomElement(PROFESSIONS),
    gender: getRandomElement(GENDERS),
    age: getRandomElement(AGES),
    health: getRandomElement(HEALTH),
    badHabit: getRandomElement(BAD_HABITS),
    hobby: getRandomElement(HOBBIES),
    luggage: getRandomElements(LUGGAGE_ITEMS, 2), // 2 предмета
    phobia: getRandomElement(PHOBIAS),
    specialInfo: getRandomElement(SPECIAL_INFO),
    fact: getRandomFact(), // 👈 ДОБАВИТЬ
  };
}

