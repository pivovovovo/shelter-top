function getRandomElement<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getRandomElements<T>(arr: T[], min: number, max: number): T[] {
  const count = min + Math.floor(Math.random() * (max - min + 1));
  const shuffled = [...arr].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function generateBunker(bunkerCapacity: number): Bunker {
  // Определяем вместимость по числу мест
  let capacityText: string;
  if (bunkerCapacity <= 3) {
    capacityText = `Тесный бункер — всего ${bunkerCapacity} мест. Каждое место на счету.`;
  } else if (bunkerCapacity <= 6) {
    capacityText = `Стандартный бункер на ${bunkerCapacity} мест. Классический баланс.`;
  } else if (bunkerCapacity <= 10) {
    capacityText = `Просторный бункер на ${bunkerCapacity} мест. Больше шансов выжить.`;
  } else {
    capacityText = `Большой бункер на ${bunkerCapacity} мест. Много пространства, но больше ресурсов нужно.`;
  }

  return {
    name: `Бункер №${Math.floor(Math.random() * 99) + 1} "${getRandomElement(BUNKER_NAMES)}"`,
    capacity: capacityText,
    layout: getRandomElements(LAYOUT_SECTIONS, 3, 6),
    supplies: {
      food: getRandomElement(FOOD_OPTIONS),
      water: getRandomElement(WATER_OPTIONS),
      fuel: getRandomElement(FUEL_OPTIONS),
      medicine: getRandomElement(MEDICINE_OPTIONS),
      weapon: getRandomElement(WEAPON_OPTIONS),
      tools: getRandomElement(TOOLS_OPTIONS),
      seeds: getRandomElement(SEEDS_OPTIONS),
      clothes: getRandomElement(CLOTHES_OPTIONS),
    },
    systems: {
      ventilation: getRandomElement(VENTILATION_OPTIONS),
      electricity: getRandomElement(ELECTRICITY_OPTIONS),
      heating: getRandomElement(HEATING_OPTIONS),
      waterFiltration: getRandomElement(WATER_FILTRATION_OPTIONS),
      airFiltration: getRandomElement(AIR_FILTRATION_OPTIONS),
      sewage: getRandomElement(SEWAGE_OPTIONS),
    },
    specialConditions: getRandomElements(SPECIAL_CONDITIONS, 1, 3),
    state: getRandomElement(BUNKER_STATES),
  };
}